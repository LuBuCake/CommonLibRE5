"""Generate include/RE/IDs_DTI.h and include/RE/IDs_VTABLE.h from the MtDTI class list.

Input: the CSV written by "Tools/Ghidra Addons/RE5 Ghidra/tools/mtdti_classes.py" (class, parent, size, flags, id,
dti, getDTI, vtable). Offsets are RVAs (VA - 0x400000), resolved at runtime by REL::Offset.
Usage: python gen_ids.py <classes.csv> <CommonLibRE5/include/RE>
"""
