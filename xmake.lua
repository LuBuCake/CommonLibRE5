-- CommonLibRE5: static library for MTFE plugins (Resident Evil 5, re5dx9.exe, x86).
-- In a plugin's xmake.lua:
--     includes("<path to>/CommonLibRE5")
--     target("MyPlugin")
--         add_rules("commonlibre5.plugin", { name = "My Plugin", author = "Me" })
--         add_files("src/**.cpp")

target("commonlibre5")
    set_kind("static")
    set_arch("x86")
    set_languages("c++23")
    set_warnings("allextra")
    set_runtimes("MT")
    add_files("src/**.cpp")
    add_headerfiles("include/(**.h)")
    add_includedirs("include", { public = true })
    add_defines("WIN32_LEAN_AND_MEAN", "NOMINMAX", { public = true })
    add_syslinks("user32", "kernel32", { public = true })
    on_config(function (target)
        if target:is_arch("x64") or target:is_arch("x86_64") then
            raise("CommonLibRE5 is 32-bit only: xmake f -p windows -a x86")
        end
    end)

rule("commonlibre5.plugin")
    on_load(function (target)
        target:set("kind", "shared")
        target:set("arch", "x86")
        target:set("runtimes", "MT")
        target:add("deps", "commonlibre5")
        target:set("languages", "c++23")

        local conf = target:extraconf("rules", "commonlibre5.plugin") or {}
        local name = conf.name or target:name()
        local author = conf.author or ""
        local version = conf.version or target:version() or "1.0.0"
        local major, minor, patch = version:match("^(%d+)%.(%d+)%.(%d+)")
        if not major then
            major, minor, patch = "1", "0", "0"
        end
        local runtimes = conf.runtimes or { "MTFE_RUNTIME_RE5_STEAM_2023" }
        local independence = conf.address_independent and "MTFE_ADDRESS_INDEPENDENT_SIGNATURES" or "0"
        local function cstr(s)
            return '"' .. s:gsub("\\", "\\\\"):gsub('"', '\\"') .. '"'
        end

        local file = path.join(target:autogendir(), "rules", "commonlibre5", "plugin_version.cpp")
        local content = format([[
// Generated by the xmake rule commonlibre5.plugin. Do not edit.
#include "MTFE/PluginAPI.h"

extern "C" __declspec(dllexport) MTFEPluginVersionData MTFEPlugin_Version = {
	MTFE_PLUGIN_VERSION_DATA_VERSION,
	MTFE_MAKE_VERSION(%s, %s, %s),
	%s,
	%s,
	%s,
	{ %s, 0 },
	MTFE_VERSION,
	{},
};
]], major, minor, patch, cstr(name), cstr(author), independence, table.concat(runtimes, ", "))
        if not os.isfile(file) or io.readfile(file) ~= content then
            io.writefile(file, content)
        end
        target:add("files", file)
    end)
