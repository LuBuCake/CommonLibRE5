#pragma once

#include "MTFE/PluginAPI.h"

#include <cstdint>
#include <functional>
#include <string>
#include <string_view>

// Entry point of an MTFE plugin:
//   MTFE_PLUGIN_LOAD(const MTFE::LoadInterface* Interface) { MTFE::Init(Interface); ...; return true; }
// The version data export (MTFEPlugin_Version) is generated by the xmake rule "commonlibre5.plugin".
#define MTFE_PLUGIN_LOAD(...) extern "C" __declspec(dllexport) bool MTFEPlugin_Load(__VA_ARGS__)

extern "C" MTFEPluginVersionData MTFEPlugin_Version;

namespace MTFE
{
    using LoadInterface = MTFELoadInterface;
    using Message = MTFEMessage;

    enum class MessageType : std::uint32_t
    {
        kPostLoad = MTFE_MESSAGE_POST_LOAD,
        kPostPostLoad = MTFE_MESSAGE_POST_POST_LOAD,
        kPreWinMain = MTFE_MESSAGE_PRE_WINMAIN,
        kGameInit = MTFE_MESSAGE_GAME_INIT,
    };

    // Call first thing in MTFEPlugin_Load. Opens <game>\MTFE\Logs\<plugin name>.log.
    void Init(const LoadInterface* Interface);

    const LoadInterface* GetLoadInterface();
    MTFEPluginHandle GetPluginHandle();
    std::string_view GetPluginName();
    std::uint32_t GetRuntimeVersion();
    std::string GetGamePath();
    std::string GetMTFEPath();

    const MTFEMessagingInterface* GetMessagingInterface();
    const MTFETaskInterface* GetTaskInterface();

    // Loader messages (sender "MTFE"). One listener per plugin is enough; switch on msg->type.
    bool RegisterListener(MTFEMessageCallback Callback);
    bool RegisterListener(const char* Sender, MTFEMessageCallback Callback);

    // Main-thread tasks (start of sMain's per-frame update). Both are thread safe.
    void AddTask(std::function<void()> Task);          // once, next frame
    void AddFrameCallback(std::function<void()> Task); // every frame from now on
}
